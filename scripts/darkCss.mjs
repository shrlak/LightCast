// The dark stylesheet of the editor, derived from its light rules (used by make-dark-css.mjs and its test).

/** Selectors that draw slides or other windows: never recoloured. */
const SKIP = /canvas|\.layer|output|stage|\.show-|motion|remote|pastor|team-|x32|presenter-out|boot-splash|qr-|chord/;
const BG = /^(background|background-color)$/;
const BORDER = /^(border|border-(top|right|bottom|left)(-color)?|border-color|outline|outline-color|column-rule|text-decoration-color)$/;
const TEXT = /^(color|caret-color|fill|stroke)$/;

const PREFIX = 'html[data-appearance="dark"]';

function hexToRgb(h) {
  let s = h.slice(1);
  if (s.length === 3 || s.length === 4) s = [...s.slice(0, 3)].map((c) => c + c).join('');
  if (s.length !== 6 && s.length !== 8) return null;
  return [0, 2, 4].map((i) => parseInt(s.slice(i, i + 2), 16));
}
function rgbToHsl([r, g, b]) {
  r /= 255; g /= 255; b /= 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b), l = (max + min) / 2;
  if (max === min) return [0, 0, l];
  const d = max - min, s = l > 0.5 ? d / (2 - max - min) : d / (max + min);
  const h = max === r ? (g - b) / d + (g < b ? 6 : 0) : max === g ? (b - r) / d + 2 : (r - g) / d + 4;
  return [h / 6, s, l];
}
function hslToHex([h, s, l]) {
  const f = (n) => {
    const k = (n + h * 12) % 12, a = s * Math.min(l, 1 - l);
    return Math.round(255 * (l - a * Math.max(-1, Math.min(k - 3, 9 - k, 1)))).toString(16).padStart(2, '0');
  };
  return `#${f(0)}${f(8)}${f(4)}`;
}

/** The dark counterpart of one colour for a kind of property, or null to leave it. */
export function darkColor(hex, kind) {
  const rgb = hexToRgb(hex);
  if (!rgb) return null;
  const [h, s, l] = rgbToHsl(rgb);
  if (kind === 'bg' && l >= 0.7) return hslToHex([h, s * 0.45, 0.12 + (1 - l) * 0.9]);
  if (kind === 'border' && l >= 0.6 && s < 0.35) return hslToHex([h, s, Math.max(0.2, 1.08 - l)]);
  if (kind === 'text' && l <= 0.45 && s < 0.3) return hslToHex([h, s, 0.92 - l * 0.5]);
  return null;
}

function mapValue(value, kind) {
  let changed = false;
  const v = value.replace(/#[0-9a-fA-F]{3,8}\b/g, (m) => {
    const d = darkColor(m, kind);
    if (!d) return m;
    changed = true;
    return d;
  }).replace(/\bwhite\b/g, (m) => { if (kind !== 'bg') return m; changed = true; return '#1f1f1f'; });
  return changed ? v : null;
}

/** Splits CSS into top-level rules (selector, body); @-blocks are left out. */
function rules(css) {
  const out = [];
  const text = css.replace(/\/\*[\s\S]*?\*\//g, '');
  let i = 0;
  while (i < text.length) {
    const open = text.indexOf('{', i);
    if (open < 0) break;
    const sel = text.slice(i, open).trim();
    let depth = 1, j = open + 1;
    while (j < text.length && depth) { if (text[j] === '{') depth++; else if (text[j] === '}') depth--; j++; }
    if (!sel.startsWith('@')) out.push([sel, text.slice(open + 1, j - 1)]);
    i = j;
  }
  return out;
}

/** Where the editor's (light) rules start in styles.css: the app around it is dark already. */
const EDITOR = '/* ================= PowerPoint-style layout ================= */';

export function darkCss(css) {
  const at = css.indexOf(EDITOR);
  const editor = at < 0 ? css : css.slice(at);
  const lines = [
    '/* Generated by scripts/make-dark-css.mjs from src/styles.css — do not edit by hand. */',
    '/* 보기 › 어두운 모드: the editor\'s light surfaces, text and borders in dark. */',
    `${PREFIX} { color-scheme: dark; }`,
    `${PREFIX} .app-ppt { --bg: #1b1a19; --panel: #252423; --panel-2: #2d2c2b; --line: #484644; --text: #f3f2f1; --muted: #c8c6c4; --accent: #4bc789; --accent-2: #6fd6a1; color-scheme: dark; }`,
  ];
  for (const [sel, body] of rules(editor)) {
    const parts = sel.split(',').map((s) => s.trim()).filter((s) => s && !SKIP.test(s) && !/^(:root|html|body|\*)/.test(s));
    if (!parts.length) continue;
    const decls = [];
    // Text on a coloured (not light grey / white) background keeps its colour: only the page around it turns dark.
    const ownBg = body.split(';').map((d) => d.split(':')).find(([p, v]) => v && BG.test(p.trim().toLowerCase()) && /#[0-9a-f]{3,8}\b|var\(/i.test(v));
    const keepText = !!ownBg && !mapValue(ownBg.slice(1).join(':'), 'bg');
    for (const d of body.split(';')) {
      const k = d.indexOf(':');
      if (k < 0) continue;
      const prop = d.slice(0, k).trim().toLowerCase();
      const val = d.slice(k + 1).trim();
      const kind = BG.test(prop) ? 'bg' : BORDER.test(prop) ? 'border' : TEXT.test(prop) ? 'text' : null;
      if (!kind || val.includes('var(') || (kind === 'text' && keepText)) continue;
      const m = mapValue(val, kind);
      if (m) decls.push(`${prop}: ${m}`);
    }
    if (decls.length) lines.push(`${parts.map((s) => `${PREFIX} ${s}`).join(', ')} { ${decls.join('; ')}; }`);
  }
  return lines.join('\n') + '\n';
}
