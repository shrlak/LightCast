/** The foreground pixels of a pattern as SVG path data in an 8×8 tile of `cell`-sized pixels. */
export function patternPath(id: string, cell = 1): string {
  const p = PATTERNS.find((x) => x.id === id);
  if (!p) return '';
  let d = '';
  p.rows.forEach((row, y) => {
    for (let x = 0; x < 8; x++) if (row & (0x80 >> x)) d += `M${x * cell} ${y * cell}h${cell}v${cell}h-${cell}z`;
  });
  return d;
}
